"""Write sw/expected.h from build/hwcase/<name>.tcl (made by gen_rt_stream.py): static configuration words and, for every window,
the seven expected counters and dense DET / LAM histogram bins 0..TOP (TOP = largest max(l_max, v_max) + 1 over the windows).
Usage: python gen_sw_header.py <name>"""
import re
import sys
from pathlib import Path

P3 = Path(__file__).resolve().parents[1]
name = sys.argv[1]
t = (P3 / "build" / "hwcase" / f"{name}.tcl").read_text()


def scalar(key):
    return int(re.search(r"set case\(%s\) (\S+)" % key, t).group(1), 0)


def arr(prefix, k):
    m = re.search(r"set %s\(%d\) \{([^}]*)\}" % (prefix, k), t)
    return [int(v) for v in m.group(1).split()]


nwin = scalar("nwin")
exp = [arr("wexp", k) for k in range(nwin)]
top = max(max(e[3], e[6]) + 1 for e in exp)
size = top + 1
det, lam = [], []
for k in range(nwin):
    for src, dst in (("wdet", det), ("wlam", lam)):
        v = arr(src, k)
        d = [0] * size
        for b, c in zip(v[0::2], v[1::2]):
            if b < size:
                d[b] = c
        dst.append(d)

out = ["/* Generated by scripts/gen_sw_header.py from %s: do not edit. SYNTHETIC test data. */" % name,
       "#define CASE_NS %d" % scalar("ns"), "#define CASE_N %d" % scalar("n"),
       "#define CASE_MX %d" % scalar("mx"), "#define CASE_TX %d" % scalar("tx"),
       "#define CASE_MY %d" % scalar("my"), "#define CASE_TY %d" % scalar("ty"),
       "#define CASE_E2X %du" % scalar("e2x"), "#define CASE_E2Y %du" % scalar("e2y"),
       "#define CASE_BASE_X %d" % scalar("base_x"), "#define CASE_BASE_Y %d" % scalar("base_y"),
       "#define NWIN %d" % nwin, "#define HIST_BINS %d" % size,
       "static const unsigned int exp_cnt[NWIN][7] = {"]
out += ["    {%s}," % ", ".join(str(v) for v in e) for e in exp]
out.append("};")
for nm, data in (("exp_det", det), ("exp_lam", lam)):
    out.append("static const unsigned int %s[NWIN][HIST_BINS] = {" % nm)
    out += ["    {%s}," % ", ".join(str(v) for v in d) for d in data]
    out.append("};")
(P3 / "sw").mkdir(exist_ok=True)
(P3 / "sw" / "expected.h").write_text("\n".join(out) + "\n")
print(f"sw/expected.h: {nwin} windows, {size} histogram bins each")
