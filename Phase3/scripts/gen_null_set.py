"""Independence-baseline experiment, step 1: random pairings of two separate recordings from cops_iridomyrmex.mat.

For each pairing k an N-sample segment of each recording is cut at an independent random start, scaled to [0, 1] (as the
export script does), and quantised to Q8.24. Each channel has its own (m, tau) and its own threshold, chosen so that the
single-channel recurrence rate is about --rr-target (a fixed-recurrence-rate threshold: the percentage-of-maximum threshold
used elsewhere gives almost no recurrences for m = 10 noise). The integer model then gives the off-diagonal recurrence counts
of the joint plot (rr_j), of channel x alone (rr_x) and of channel y alone (rr_y). The board is asked for the same three counts
(joint run, x-only run with eps_y = max, y-only run with eps_x = max) and must equal them exactly.

Writes build/rtcase/null_<name>.bin (OCM image: window k at byte offset k*N*8), sw/null_tables.h (per-window parameters and
expected counts) and build/hwcase/null_<name>.json (expected counts and parameters, for analyse_null.py).
Usage: python gen_null_set.py --pair darwin_lab --nwin 24 --n 1024 --seed 1
"""
import argparse
import json
import struct
import sys
from pathlib import Path

import numpy as np
from scipy.io import loadmat

P3 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(P3.parent / "Phase1" / "src"))
from jrp import fixedpoint as fp  # noqa: E402
from jrp.jrp import ChannelParams, embed_pair  # noqa: E402
from jrp.signals import to_unit_interval  # noqa: E402

MAT = P3.parent / "cops_iridomyrmex.mat"
SERIES = {"darwin": ("acinaciformis_Darwin", 10, 1), "griffith": ("acinaciformis_Griffith", 10, 1), "lab": ("purpureus_lab", 5, 4)}


def offdiag_count(R):
    R0 = np.array(R, dtype=np.uint8, copy=True)
    np.fill_diagonal(R0, 0)
    return int(R0.sum())


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--pair", required=True, help="e.g. darwin_lab, griffith_lab, darwin_griffith")
    a.add_argument("--nwin", type=int, default=24)
    a.add_argument("--n", type=int, default=1024)
    a.add_argument("--seed", type=int, default=1)
    a.add_argument("--rr-target", type=float, default=0.10)
    args = a.parse_args()
    if args.nwin * args.n * 8 > 196608:
        raise SystemExit("does not fit the 192 KB of OCM available to the bare-metal program")
    ka, kb = args.pair.split("_")
    (na, mx, tx), (nb, my, ty) = SERIES[ka], SERIES[kb]
    d = loadmat(MAT, squeeze_me=True)
    A, B = d[na], d[nb]
    rng = np.random.default_rng(args.seed)
    N = args.n
    px, py = ChannelParams(mx, tx, eps_percent=10.0), ChannelParams(my, ty, eps_percent=10.0)
    rows, img = [], bytearray()
    for k in range(args.nwin):
        sa, sb = int(rng.integers(0, len(A) - N)), int(rng.integers(0, len(B) - N))
        x = to_unit_interval(A[sa:sa + N] - A[sa:sa + N].mean())
        y = to_unit_interval(B[sb:sb + N] - B[sb:sb + N].mean())
        xq, yq = fp.to_q824(x), fp.to_q824(y)
        Vx, Vy = embed_pair(x, y, px, py)
        n = Vx.shape[0]
        e2 = []
        for V in (Vx, Vy):
            i = rng.integers(0, n, 4000); j = rng.integers(0, n, 4000)
            keep = i != j
            dist = np.linalg.norm(V[i[keep]] - V[j[keep]], axis=1)
            e2.append(fp.eps2_to_q824(float(np.quantile(dist, args.rr_target))))
        Vqx, Vqy = embed_pair(xq, yq, px, py)
        Vqx, Vqy = Vqx.astype(np.int64), Vqy.astype(np.int64)
        Rx, Ry = fp.recurrence_flags_q824(Vqx, e2[0]), fp.recurrence_flags_q824(Vqy, e2[1])
        nxv, nyv = N - (mx - 1) * tx, N - (my - 1) * ty
        rows.append(dict(k=k, start_a=sa, start_b=sb, mx=mx, tx=tx, my=my, ty=ty, e2x=int(e2[0]), e2y=int(e2[1]), n=n,
                         base_x=nxv - n, base_y=nyv - n, rr_j=offdiag_count(Rx & Ry), rr_x=offdiag_count(Rx), rr_y=offdiag_count(Ry)))
        for xv, yv in zip(xq, yq):
            img += struct.pack("<II", int(xv) & 0xFFFFFFFF, int(yv) & 0xFFFFFFFF)
    name = f"{args.pair}_s{args.seed}"
    (P3 / "build" / "rtcase").mkdir(parents=True, exist_ok=True)
    (P3 / "build" / "rtcase" / f"null_{name}.bin").write_bytes(bytes(img))
    (P3 / "build" / "hwcase").mkdir(parents=True, exist_ok=True)
    (P3 / "build" / "hwcase" / f"null_{name}.json").write_text(json.dumps(dict(name=name, n_samples=N, rr_target=args.rr_target, rows=rows), indent=1))
    h = ["/* generated by scripts/gen_null_set.py: %s */" % name, "#define NWIN %d" % args.nwin, "#define NS %d" % N]
    for key in ("mx", "tx", "my", "ty", "e2x", "e2y", "n", "base_x", "base_y", "rr_j", "rr_x", "rr_y"):
        h.append("static const unsigned int T_%s[NWIN] = {%s};" % (key, ", ".join(str(r[key]) + "u" for r in rows)))
    (P3 / "sw" / "null_tables.h").write_text("\n".join(h) + "\n")
    r = np.array([[q["rr_j"], q["rr_x"], q["rr_y"], q["n"]] for q in rows], dtype=float)
    ok = (r[:, 1] > 0) & (r[:, 2] > 0)
    ratio = r[ok, 0] * r[ok, 3] ** 2 / (r[ok, 1] * r[ok, 2])
    print(f"{name}: {args.nwin} pairings of {N} samples ({na} x {nb}), model ratio JRR/(RRx RRy): median {np.median(ratio):.3f}, "
          f"range [{ratio.min():.3f}, {ratio.max():.3f}]; rr_x median {np.median(r[:, 1] / r[:, 3] ** 2):.4f}, rr_y {np.median(r[:, 2] / r[:, 3] ** 2):.4f}")


if __name__ == "__main__":
    main()
