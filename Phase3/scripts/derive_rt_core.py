"""Generate rtl/jrp_rt_core.v from rtl/jrp_board_core.v: same register map and decoder, but target 3 (0x60000) is
jrp_rt_ingest (ring FIFO + frame sequencer) instead of the JTAG-filled sample feeder, the sample stream comes in
on an AXI-Stream slave port (AXI-DMA) and a result interrupt is exported. Run after any edit of jrp_board_core.v."""
from pathlib import Path

rtl = Path(__file__).resolve().parents[1] / "rtl"
s = (rtl / "jrp_board_core.v").read_text()


def rep(old, new):
    global s
    assert s.count(old) == 1, old
    s = s.replace(old, new)


rep("module jrp_board_core #(", "module jrp_rt_core #(")
rep("ASSOCIATED_BUSIF s_axi,", "ASSOCIATED_BUSIF s_axi:s_axis_samples,")
rep("    parameter integer K     = 1     // 1: one pair per cycle, 2: two cells per cycle\n)(",
    "    parameter integer K     = 1,    // 1: one pair per cycle, 2: two cells per cycle\n"
    "    parameter integer RING_DEPTH = 8192\n)(")
rep("    input  wire [31:0] s_axi_wdata,  input  wire [3:0] s_axi_wstrb, input wire s_axi_wvalid, output wire s_axi_wready,",
    "    input  wire [31:0] s_axi_wdata,  input  wire [3:0] s_axi_wstrb, input wire s_axi_wvalid, output wire s_axi_wready,")
rep("    output wire [31:0] s_axi_rdata,  output wire [1:0] s_axi_rresp, output wire s_axi_rvalid, input wire s_axi_rready\n);",
    "    output wire [31:0] s_axi_rdata,  output wire [1:0] s_axi_rresp, output wire s_axi_rvalid, input wire s_axi_rready,\n\n"
    "    // sample stream {y, x} from AXI-DMA MM2S, and the result-ready interrupt\n"
    "    input  wire [63:0] s_axis_samples_tdata, input wire s_axis_samples_tvalid, output wire s_axis_samples_tready,\n"
    "    input  wire        s_axis_samples_tlast,\n"
    "    output wire        irq\n);")

i0 = s.index("    // ---- sample feeder -> jrp_top ----")
i1 = s.index("    // ---- the design under test ----")
s = s[:i0] + """    // ---- ring FIFO and frame sequencer -> jrp_top ----
    wire [63:0] samp_tdata; wire samp_tvalid, samp_tready, samp_tlast;
    wire rt_ext_start, top_busy, top_done, top_cfg_err; wire [31:0] top_nraw;
    jrp_rt_ingest #(.DEPTH(RING_DEPTH)) u_rt (
        .clk(clk), .rst_n(rst_n),
        .s_axi_awaddr(m_awaddr[5:0]), .s_axi_awvalid(m_awvalid[3]), .s_axi_awready(m_awready[3]),
        .s_axi_wdata(m_wdata), .s_axi_wstrb(m_wstrb), .s_axi_wvalid(m_wvalid[3]), .s_axi_wready(m_wready[3]),
        .s_axi_bresp(t_bresp[3]), .s_axi_bvalid(m_bvalid[3]), .s_axi_bready(m_bready[3]),
        .s_axi_araddr(m_araddr[5:0]), .s_axi_arvalid(m_arvalid[3]), .s_axi_arready(m_arready[3]),
        .s_axi_rdata(t_rdata[3]), .s_axi_rresp(t_rresp[3]), .s_axi_rvalid(m_rvalid[3]), .s_axi_rready(m_rready[3]),
        .s_axis_tdata(s_axis_samples_tdata), .s_axis_tvalid(s_axis_samples_tvalid), .s_axis_tready(s_axis_samples_tready),
        .s_axis_tlast(s_axis_samples_tlast),
        .m_axis_tdata(samp_tdata), .m_axis_tvalid(samp_tvalid), .m_axis_tready(samp_tready), .m_axis_tlast(samp_tlast),
        .ext_start(rt_ext_start), .top_busy(top_busy), .top_result(top_done), .top_cfg_err(top_cfg_err),
        .n_raw(top_nraw), .cyc(cyc), .irq(irq));

""" + s[i1:]
rep(".clk(clk), .rst_n(rst_n), .ext_start(1'b0), .frame_busy(), .frame_done_pulse(), .frame_cfg_err(), .n_raw_o(),",
    ".clk(clk), .rst_n(rst_n), .ext_start(rt_ext_start), .frame_busy(top_busy), .frame_done_pulse(top_done),\n"
    "        .frame_cfg_err(top_cfg_err), .n_raw_o(top_nraw),")
rep("//   Bring-up top for the AXU5EVB-P: jrp_top + sample feeder + clock counter behind ONE AXI4-Lite",
    "//   GENERATED by scripts/derive_rt_core.py from jrp_board_core.v. Real-time top: jrp_top + jrp_rt_ingest (target 3,\n"
    "//   0x60000, replaces the sample feeder) + clock counter behind ONE AXI4-Lite")
(rtl / "jrp_rt_core.v").write_text(s)
print("wrote", rtl / "jrp_rt_core.v")
